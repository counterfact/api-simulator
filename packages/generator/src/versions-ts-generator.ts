import ts from "typescript";

import {
  formatStatements,
  literalType,
  parameter,
  typeAlias,
  typeLiteral,
  typeProperty,
  typeReference,
  unionType,
  withJsDoc,
} from "./ast.js";

function buildVersionsGTE(
  versions: readonly string[],
): Map<string, readonly string[]> {
  return new Map(
    versions.map((version, index) => [version, versions.slice(index)]),
  );
}

const VERSIONED_DESCRIPTION = `The type of the \u0060$\u0060 argument in a versioned route handler.

@typeParam T - A map from version string to the \u0060$\u0060-arg type for that version
  (e.g. \u0060{ v1: $v1Type; v2: $v2Type }\u0060). Generated by Counterfact from the spec.
@typeParam V - The union of currently active version keys; defaults to all keys of \u0060T\u0060.

An instance of \u0060Versioned<T, V>\u0060 exposes:
- All properties of the intersection \u0060T[V]\u0060 (request data, response builders, etc.)
- \u0060version\u0060 — the version string for the current request (e.g. \u0060"v2"\u0060).
- \u0060minVersion(min)\u0060 — type predicate that returns \u0060true\u0060 when the current version
  is at or after \u0060min\u0060 in the declared version order and narrows \u0060$\u0060 accordingly.`;

export async function generateVersionsTsContent(
  versions: readonly string[],
): Promise<string> {
  if (versions.length === 0) return "";
  const activeKeys = () =>
    ts.factory.createIntersectionTypeNode([
      ts.factory.createTypeOperatorNode(
        ts.SyntaxKind.KeyOfKeyword,
        typeReference("T"),
      ),
      typeReference("Versions"),
    ]);
  const activeVersionMap = ts.factory.createIndexedAccessTypeNode(
    typeReference("VersionsGTE"),
    typeReference("M"),
  );
  const narrowing = ts.factory.createTypePredicateNode(
    undefined,
    ts.factory.createThisTypeNode(),
    typeReference("Versioned", [
      typeReference("T"),
      typeReference("Extract", [typeReference("V"), activeVersionMap]),
    ]),
  );
  const minVersion = ts.factory.createMethodSignature(
    undefined,
    "minVersion",
    undefined,
    [ts.factory.createTypeParameterDeclaration(undefined, "M", activeKeys())],
    [parameter("min", typeReference("M"))],
    narrowing,
  );
  return formatStatements(
    [
      withJsDoc(typeAlias("Versions", unionType(versions.map(literalType))), {
        description:
          'Union of all version strings declared for this API group (e.g. \u0060"v1" | "v2" | "v3"\u0060).',
      }),
      withJsDoc(
        typeAlias(
          "VersionsGTE",
          typeLiteral(
            [...buildVersionsGTE(versions)].map(([version, newer]) =>
              typeProperty(version, unionType(newer.map(literalType))),
            ),
            true,
          ),
        ),
        {
          description:
            "Maps each version to the set of versions that are greater than or equal to it.\nUsed by \u0060Versioned.minVersion()\u0060 to narrow which versions a handler must support.",
        },
      ),
      typeAlias(
        "VersionMap",
        typeReference("Partial", [
          typeReference("Record", [
            typeReference("Versions"),
            ts.factory.createKeywordTypeNode(ts.SyntaxKind.ObjectKeyword),
          ]),
        ]),
        false,
      ),
      withJsDoc(
        typeAlias(
          "Versioned",
          ts.factory.createIntersectionTypeNode([
            ts.factory.createIndexedAccessTypeNode(
              typeReference("T"),
              typeReference("V"),
            ),
            typeLiteral(
              [typeProperty("version", typeReference("V")), minVersion],
              true,
            ),
          ]),
          true,
          [
            ts.factory.createTypeParameterDeclaration(
              undefined,
              "T",
              typeReference("VersionMap"),
            ),
            ts.factory.createTypeParameterDeclaration(
              undefined,
              "V",
              activeKeys(),
              activeKeys(),
            ),
          ],
        ),
        { description: VERSIONED_DESCRIPTION },
      ),
    ],
    ["This file is auto-generated by Counterfact. Do not edit."],
  );
}
