import { CHOKIDAR_OPTIONS } from "./watch-options.js";

interface ContextFileInfo {
  importPath: string;
  alias: string;
  routePath: string;
  depth: number;
}

interface RouteDirectoryInfo {
  relativePath: string;
  contextFile?: string;
}

const GENERATED_FILE_COMMENT =
  "// This file is generated by Counterfact. Do not edit manually.";

async function collectContextFiles(
  destination: string,
): Promise<ContextFileInfo[]> {
  const routesDir = nodePath.join(destination, "routes");
  const results: ContextFileInfo[] = [];

  if (!existsSync(routesDir)) {
    return results;
  }

  await walkForContextFiles(routesDir, routesDir, results);
  results.sort((a, b) => b.depth - a.depth);
  const names = new Set<string>();
  for (const context of results) {
    const base = /^\d/u.test(context.alias)
      ? "_" + context.alias
      : context.alias;
    let name = base;
    let suffix = 2;
    while (names.has(name)) name = base + suffix++;
    context.alias = name;
    names.add(name);
  }

  return results;
}

async function walkForContextFiles(
  routesDir: string,
  currentDir: string,
  results: ContextFileInfo[],
): Promise<void> {
  let entries: Dirent[];

  try {
    entries = await fs.readdir(currentDir, { withFileTypes: true });
  } catch {
    return;
  }

  for (const entry of entries) {
    if (entry.isDirectory()) {
      await walkForContextFiles(
        routesDir,
        nodePath.join(currentDir, entry.name),
        results,
      );
    } else if (entry.name === "_.context.ts") {
      const relDir = pathRelative(routesDir, currentDir);
      const routePath = relDir === "" ? "/" : `/${relDir}`;
      const depth = relDir === "" ? 0 : relDir.split("/").length;
      const importPath =
        relDir === "" ? "../routes/_.context" : `../routes/${relDir}/_.context`;
      const alias = routePathToAlias(routePath);
      results.push({ importPath, alias, routePath, depth });
    }
  }
}

async function collectRouteDirectories(
  destination: string,
): Promise<RouteDirectoryInfo[]> {
  const routesDir = nodePath.join(destination, "routes");

  if (!existsSync(routesDir)) {
    return [];
  }

  const results: RouteDirectoryInfo[] = [];

  await walkRouteDirectories(routesDir, routesDir, undefined, results);

  return results;
}

async function walkRouteDirectories(
  routesDir: string,
  currentDir: string,
  inheritedContextFile: string | undefined,
  results: RouteDirectoryInfo[],
): Promise<void> {
  let entries: Dirent[];

  try {
    entries = await fs.readdir(currentDir, { withFileTypes: true });
  } catch {
    return;
  }

  const localContextFile = entries.some(
    (entry) => entry.isFile() && entry.name === "_.context.ts",
  )
    ? nodePath.join(currentDir, "_.context.ts")
    : inheritedContextFile;

  results.push({
    contextFile: localContextFile,
    relativePath: pathRelative(routesDir, currentDir),
  });

  for (const entry of entries) {
    if (entry.isDirectory()) {
      await walkRouteDirectories(
        routesDir,
        nodePath.join(currentDir, entry.name),
        localContextFile,
        results,
      );
    }
  }
}

function routePathToAlias(routePath: string): string {
  if (routePath === "/") {
    return "Context";
  }

  return (
    routePath
      .split("/")
      .filter(Boolean)
      .map((seg) =>
        seg
          .replace(/\{(.+?)\}/g, (_match, name: string) =>
            name.replace(/[^a-z0-9]/gi, " "),
          )
          .replace(/[-_\s]([a-z])/g, (_match, c: string) => c.toUpperCase())
          .replace(/^[a-z]/, (c) => c.toUpperCase())
          .replace(/[^a-z0-9]/gi, ""),
      )
      .join("") + "Context"
  );
}

const PARAM_SEGMENT_REGEX = /^\{.+\}$/u;

function pathTemplate(parts: readonly string[]): ts.TemplateLiteralTypeNode {
  const fragments = [""];
  const placeholders: ts.TypeNode[] = [];
  for (const part of parts) {
    fragments[fragments.length - 1] += "/";
    if (PARAM_SEGMENT_REGEX.test(part)) {
      placeholders.push(stringType());
      fragments.push("");
    } else {
      fragments[fragments.length - 1] += part;
    }
  }
  return ts.factory.createTemplateLiteralType(
    ts.factory.createTemplateHead(fragments[0]!),
    placeholders.map((type, index) =>
      ts.factory.createTemplateLiteralTypeSpan(
        type,
        index === placeholders.length - 1
          ? ts.factory.createTemplateTail(fragments[index + 1]!)
          : ts.factory.createTemplateMiddle(fragments[index + 1]!),
      ),
    ),
  );
}

function buildLoadContextOverload(
  routePath: string,
  alias: string,
): ts.MethodSignature {
  const segments = routePath.split("/").filter(Boolean);
  const path = segments.some((segment) => PARAM_SEGMENT_REGEX.test(segment))
    ? pathTemplate(segments)
    : unionType([
        literalType(routePath),
        ts.factory.createTemplateLiteralType(
          ts.factory.createTemplateHead(
            routePath === "/" ? "/" : routePath + "/",
          ),
          [
            ts.factory.createTemplateLiteralTypeSpan(
              stringType(),
              ts.factory.createTemplateTail(""),
            ),
          ],
        ),
      ]);
  return ts.factory.createMethodSignature(
    undefined,
    "loadContext",
    undefined,
    undefined,
    [parameter("path", path)],
    typeReference(alias),
  );
}

function recordType(): ts.TypeNode {
  return typeReference("Record", [stringType(), unknownType()]);
}

function interfaceDeclaration(
  name: string,
  members: readonly ts.TypeElement[],
  exported: boolean,
): ts.InterfaceDeclaration {
  return ts.factory.createInterfaceDeclaration(
    exported
      ? [ts.factory.createModifier(ts.SyntaxKind.ExportKeyword)]
      : undefined,
    name,
    undefined,
    undefined,
    members,
  );
}

async function buildScenarioContextContent(
  contextFiles: ContextFileInfo[],
  storeImportPath?: string,
): Promise<string> {
  const rootContext = contextFiles.find((file) => file.routePath === "/");
  const imports = contextFiles.map(({ importPath, alias }) =>
    importDeclaration(alias, importPath, true, false, "Context"),
  );
  if (storeImportPath !== undefined)
    imports.push(importDeclaration("Store", storeImportPath, true));
  const loadContext = () =>
    ts.factory.createIndexedAccessTypeNode(
      typeReference("LoadContextDefinitions"),
      literalType("loadContext"),
    );
  const voidType = () =>
    ts.factory.createKeywordTypeNode(ts.SyntaxKind.VoidKeyword);
  const overloads = contextFiles.map(({ alias, routePath }) =>
    buildLoadContextOverload(routePath, alias),
  );
  const fallback = ts.factory.createMethodSignature(
    undefined,
    "loadContext",
    undefined,
    undefined,
    [parameter("path", stringType())],
    recordType(),
  );
  return formatStatements(
    [
      ...imports,
      interfaceDeclaration(
        "LoadContextDefinitions",
        [...overloads, fallback],
        false,
      ),
      interfaceDeclaration(
        "Scenario$",
        [
          readonlyProperty(
            "context",
            rootContext ? typeReference(rootContext.alias) : recordType(),
            'Root context, same as loadContext("/")',
          ),
          readonlyProperty(
            "loadContext",
            loadContext(),
            "Load a context object for a specific path",
          ),
          readonlyProperty(
            "routes",
            recordType(),
            "Named route builders stored in the REPL execution context",
          ),
          readonlyProperty(
            "route",
            functionType([parameter("path", stringType())], unknownType()),
            "Create a new route builder for a given path",
          ),
        ],
        true,
      ),
      withJsDoc(
        typeAlias(
          "Scenario",
          functionType(
            [parameter("$", typeReference("Scenario$"))],
            unionType([typeReference("Promise", [voidType()]), voidType()]),
          ),
        ),
        {
          description:
            "A scenario function that receives the live REPL environment",
        },
      ),
      withJsDoc(
        interfaceDeclaration(
          "Context$",
          [
            ...(storeImportPath === undefined
              ? []
              : [
                  readonlyProperty(
                    "store",
                    typeReference("Store"),
                    "Application-level store shared by every API group",
                  ),
                ]),
            readonlyProperty(
              "loadContext",
              loadContext(),
              "Load a context object for a specific path",
            ),
            readonlyProperty(
              "readJson",
              functionType(
                [parameter("relativePath", stringType())],
                typeReference("Promise", [unknownType()]),
              ),
              "Load a JSON file relative to this file's path",
            ),
          ],
          true,
        ),
        {
          description:
            "Interface for Context objects defined in _.context.ts files",
        },
      ),
    ],
    [GENERATED_FILE_COMMENT.slice(3)],
  );
}

function ensureRelativeImportPath(path: string): string {
  return path.startsWith(".") ? path : "./" + path;
}

async function buildMiddlewareTypeContent(
  destination: string,
  routeDirectory: RouteDirectoryInfo,
): Promise<string> {
  const directory = nodePath.join(
    destination,
    "types",
    routeDirectory.relativePath,
  );
  const sharedPath = ensureRelativeImportPath(
    pathRelative(
      directory,
      nodePath.join(destination, "counterfact-types", "index.js"),
    ),
  );
  const statements: ts.Statement[] = [
    importDeclaration(
      "MiddlewareFunction",
      sharedPath,
      true,
      false,
      "Middleware",
    ),
  ];
  const arguments_: ts.TypeNode[] = [];
  if (routeDirectory.contextFile !== undefined) {
    const contextPath = ensureRelativeImportPath(
      pathRelative(directory, routeDirectory.contextFile).replace(
        /\.ts$/u,
        ".js",
      ),
    );
    statements.push(importDeclaration("Context", contextPath, true));
    arguments_.push(typeReference("Context"));
  }
  statements.push(
    typeAlias("Middleware", typeReference("MiddlewareFunction", arguments_)),
  );
  return formatStatements(statements, [GENERATED_FILE_COMMENT.slice(3)]);
}

async function collectGeneratedMiddlewareTypeFiles(
  directory: string,
): Promise<string[]> {
  let entries: Dirent[];

  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch {
    return [];
  }

  const files: string[] = [];

  for (const entry of entries) {
    const path = nodePath.join(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await collectGeneratedMiddlewareTypeFiles(path)));
    } else if (entry.name === "_.middleware.ts") {
      const content = await fs.readFile(path, "utf8");

      if (content.startsWith(GENERATED_FILE_COMMENT)) {
        files.push(path);
      }
    }
  }

  return files;
}

async function writeMiddlewareTypes(destination: string): Promise<void> {
  const routeDirectories = await collectRouteDirectories(destination);
  const expectedFiles = new Set<string>();

  for (const routeDirectory of routeDirectories) {
    const filePath = nodePath.join(
      destination,
      "types",
      routeDirectory.relativePath,
      "_.middleware.ts",
    );
    expectedFiles.add(nodePath.resolve(filePath));
    await fs.mkdir(nodePath.dirname(filePath), { recursive: true });
    await fs.writeFile(
      filePath,
      await buildMiddlewareTypeContent(destination, routeDirectory),
      "utf8",
    );
  }

  const generatedFiles = await collectGeneratedMiddlewareTypeFiles(
    nodePath.join(destination, "types"),
  );

  await Promise.all(
    generatedFiles
      .filter((file) => !expectedFiles.has(nodePath.resolve(file)))
      .map((file) => fs.rm(file)),
  );
}

/**
 * Writes the `types/_.context.ts` file, which exports the
 * `Scenario$` interface used to type scenario functions.
 *
 * The interface is generated from all `_.context.ts` files found under the
 * `routes/` directory, providing strongly typed `loadContext()` overloads for
 * every route path that has a context file.
 *
 * @param destination - Root output directory.
 * @param rootDestination - Application root containing the optional store.
 */
async function writeScenarioContextType(
  destination: string,
  rootDestination: string,
): Promise<void> {
  const typesDir = nodePath.join(destination, "types");
  const filePath = nodePath.join(typesDir, "_.context.ts");
  const storePath = nodePath.join(rootDestination, "_.store.ts");

  const contextFiles = await collectContextFiles(destination);
  const relativeStorePath = pathRelative(typesDir, storePath);
  const storeImportPath = existsSync(storePath)
    ? `${relativeStorePath.startsWith(".") ? "" : "./"}${relativeStorePath.replace(/\.ts$/u, ".js")}`
    : undefined;
  const content = await buildScenarioContextContent(
    contextFiles,
    storeImportPath,
  );

  await fs.mkdir(typesDir, { recursive: true });
  await fs.writeFile(filePath, content, "utf8");
}

async function defaultScenariosContent(): Promise<string> {
  const arrow = (statements: readonly ts.Statement[]) =>
    ts.factory.createArrowFunction(
      undefined,
      undefined,
      [parameter("$")],
      undefined,
      ts.factory.createToken(ts.SyntaxKind.EqualsGreaterThanToken),
      ts.factory.createBlock(statements, true),
    );
  const ignoreArgument = () =>
    ts.factory.createExpressionStatement(
      ts.factory.createVoidExpression(ts.factory.createIdentifier("$")),
    );
  const log = (expression: ts.Expression) =>
    ts.factory.createExpressionStatement(
      ts.factory.createCallExpression(
        ts.factory.createPropertyAccessExpression(
          ts.factory.createIdentifier("console"),
          "log",
        ),
        undefined,
        [expression],
      ),
    );
  const lines = valueExpression([
    "Scenarios are functions that populate the context object",
    "and / or the REPL environment. They are intended to",
    "populate your environment with specific data and",
    "configurations for testing purposes.",
  ]);
  const joinedLines = ts.factory.createCallExpression(
    ts.factory.createPropertyAccessExpression(lines, "join"),
    undefined,
    [valueExpression("\n")],
  );
  return formatStatements([
    importDeclaration("Scenario", "../types/_.context.js", true),
    withJsDoc(
      exportedConst(
        "startup",
        arrow([ignoreArgument()]),
        typeReference("Scenario"),
      ),
      {
        description:
          "Scenario scripts are plain TypeScript functions that receive the live REPL\n" +
          "environment and can read or mutate server state. Run them from the REPL with:\n" +
          "  .scenario <functionName>\n\n" +
          "Read or mutate the root context (same object routes see as $.context):\n" +
          "  $.context.<property> = <value>;\n\n" +
          "Load a context for a specific path:\n" +
          '  const petsCtx = $.loadContext("/pets");\n\n' +
          "Store a pre-configured route builder for later use in the REPL:\n" +
          '  $.routes.myRequest = $.route("/pets").method("get");\n\n' +
          "startup() runs automatically when the server initializes, right before the\n" +
          "REPL starts. Use it to seed dummy data so the server is ready to use\n" +
          "immediately. It receives the same $ argument as all other scenario functions.\n\n" +
          "Tip: delegate to other scenario functions and pass $ along so each function\n" +
          "stays focused on a single concern. You can also pass additional arguments to\n" +
          'configure them, e.g. addPets($, 20, "dog").\n\n' +
          "If you don't need a startup scenario, delete this function or leave it empty.",
      },
    ),
    withJsDoc(
      exportedConst(
        "help",
        arrow([
          ignoreArgument(),
          log(joinedLines),
          log(
            valueExpression(
              "\nScenarios (including this one) are defined in the ./scenarios directory.",
            ),
          ),
        ]),
        typeReference("Scenario"),
      ),
      {
        description:
          "An example scenario. To use it in the REPL, type:\n  .scenario help",
      },
    ),
  ]);
}

async function writeDefaultScenariosIndex(destination: string): Promise<void> {
  const scenariosDir = nodePath.join(destination, "scenarios");
  const filePath = nodePath.join(scenariosDir, "index.ts");

  if (existsSync(filePath)) {
    return;
  }

  await fs.mkdir(scenariosDir, { recursive: true });
  await fs.writeFile(filePath, await defaultScenariosContent(), "utf8");
}

/**
 * Encapsulates the generation of scenario-related files:
 * - `types/_.context.ts` — the typed `Scenario$` interface derived from all
 *   `_.context.ts` files found under `routes/`.
 * - `scenarios/index.ts` — the default scenarios entry-point (created only if
 *   it does not already exist).
 *
 * When {@link watch} is called, file-system watchers monitor the `routes/`
 * directory for changes to `_.context.ts` files and the application root's
 * optional `_.store.ts`, automatically regenerating `types/_.context.ts` and
 * the mirrored `_.middleware.ts` files under `types/`.
 */
export class ScenarioFileGenerator {
  private readonly destination: string;

  private readonly rootDestination: string;

  private watcher: FSWatcher | undefined;

  private storeWatcher: FSWatcher | undefined;

  public constructor(destination: string, rootDestination = destination) {
    this.destination = destination;
    this.rootDestination = rootDestination;
  }

  /** Generates both scenario-related files once and resolves when complete. */
  public async generate(): Promise<void> {
    await writeScenarioContextType(this.destination, this.rootDestination);
    await writeMiddlewareTypes(this.destination);
    await writeDefaultScenariosIndex(this.destination);
  }

  /**
   * Starts watching route context files and the exact application-root store
   * path, regenerating `types/_.context.ts` and the mirrored `_.middleware.ts`
   * files under `types/` on every relevant change.
   *
   * Resolves once the watcher is ready.
   */
  public async watch(): Promise<void> {
    const routesDir = nodePath.join(this.destination, "routes");
    const storePath = nodePath.join(this.rootDestination, "_.store.ts");
    const regenerate = (): void => {
      void Promise.all([
        writeScenarioContextType(this.destination, this.rootDestination),
        writeMiddlewareTypes(this.destination),
      ]).catch((error: unknown) => {
        console.error("Failed to regenerate scenario files:", error);
      });
    };

    this.watcher = watch(routesDir, CHOKIDAR_OPTIONS).on(
      "all",
      (event, filePath: string) => {
        if (
          filePath.endsWith("_.context.ts") ||
          event === "addDir" ||
          event === "unlinkDir"
        ) {
          regenerate();
        }
      },
    );

    // Polling lets chokidar observe creation of the exact conventional store
    // path even when the file is absent when the watcher starts.
    this.storeWatcher = watch(storePath, {
      ...CHOKIDAR_OPTIONS,
      usePolling: true,
    }).on("all", (_event, filePath: string) => {
      if (nodePath.resolve(filePath) === nodePath.resolve(storePath)) {
        regenerate();
      }
    });

    await Promise.all([
      waitForEvent(this.watcher, "ready"),
      waitForEvent(this.storeWatcher, "ready"),
    ]);
  }

  /** Closes the file-system watcher. */
  public async stopWatching(): Promise<void> {
    await Promise.all([this.watcher?.close(), this.storeWatcher?.close()]);
  }
}
