/** Options for generating a typed API client. */
export interface ClientGenerationOptions extends ClientGroupingOptions {
  /** Name of the class that combines every module (default `Api`). */
  apiClassName?: string;
  /** Prepended to every data contract type name. */
  typePrefix?: string;
  /** Appended to every data contract type name, e.g. `Dto` for `UserDto`. */
  typeSuffix?: string;
  /** Resolve each method with the response body instead of the response. */
  unwrapResponseData?: boolean;
  /**
   * Generate a client that does not depend on the rest of the generated
   * project: request and response types are written inline, and every schema
   * is declared in its own file under `client/data-contracts/`.
   */
  standalone?: boolean;
}

/** Directory, relative to the generated project, that holds the client. */
export const CLIENT_DIRECTORY = "client";

const GENERATED_COMMENTS = [
  "This code was automatically generated by Counterfact.",
  "Do not edit this file. It is replaced whenever the client is regenerated.",
  "For more information, see https://counterfact.dev",
];

const f = ts.factory;

function exportModifier(): ts.ModifierLike[] {
  return [f.createModifier(ts.SyntaxKind.ExportKeyword)];
}

function namedImport(
  names: readonly string[],
  modulePath: string,
  isTypeOnly: boolean,
): ts.ImportDeclaration {
  return f.createImportDeclaration(
    undefined,
    f.createImportClause(
      isTypeOnly,
      undefined,
      f.createNamedImports(
        names.map((name) =>
          f.createImportSpecifier(false, undefined, f.createIdentifier(name)),
        ),
      ),
    ),
    f.createStringLiteral(modulePath),
  );
}

/**
 * `public readonly http: HttpProvider;` plus a constructor that takes the
 * provider, defaulting to the fetch-based `HttpClient`. Configuration (base
 * URL, credentials, headers, custom fetch) lives entirely in the provider.
 */
function providerMembers(
  initialization: readonly ts.Statement[] = [],
): ts.ClassElement[] {
  return [
    f.createPropertyDeclaration(
      [
        f.createModifier(ts.SyntaxKind.PublicKeyword),
        f.createModifier(ts.SyntaxKind.ReadonlyKeyword),
      ],
      "http",
      undefined,
      typeReference("HttpProvider"),
      undefined,
    ),
    f.createConstructorDeclaration(
      [f.createModifier(ts.SyntaxKind.PublicKeyword)],
      [
        f.createParameterDeclaration(
          undefined,
          undefined,
          "http",
          undefined,
          typeReference("HttpProvider"),
          f.createNewExpression(
            f.createIdentifier("HttpClient"),
            undefined,
            [],
          ),
        ),
      ],
      f.createBlock(
        [
          f.createExpressionStatement(
            f.createAssignment(
              f.createPropertyAccessExpression(f.createThis(), "http"),
              f.createIdentifier("http"),
            ),
          ),
          ...initialization,
        ],
        true,
      ),
    ),
  ];
}

function jsDoc(lines: readonly string[]): string {
  // Values from the document, such as a summary, can span several lines.
  return `/**\n${lines
    .flatMap((line) => line.split(/\r?\n/u))
    .map((line) => ` * ${line.replaceAll("*/", "* /")}`)
    .join("\n")}\n */`;
}

function operationJsDoc(operation: ClientOperation): string {
  return jsDoc([
    ...(operation.description === undefined
      ? []
      : operation.description
          .split("\n")
          .map((line, index) => (index === 0 ? `@description ${line}` : line))),
    ...(operation.tags.length === 0
      ? []
      : [`@tags ${operation.tags.join(", ")}`]),
    `@name ${pascalCase(operation.name)}`,
    ...(operation.summary === undefined
      ? []
      : [`@summary ${operation.summary}`]),
    `@request ${operation.method.toUpperCase()}:${operation.path}`,
    ...(operation.secure ? ["@secure"] : []),
    ...(operation.deprecated ? ["@deprecated"] : []),
  ]);
}

function operationTypeName(operation: ClientOperation): string {
  return `${pascalCase(operation.name)}Operation`;
}

/** `/users/{userId}` → `` `/users/${encodeURIComponent(String(userId))}` `` */
function pathExpression(
  path: string,
  identifiers: ReadonlyMap<string, string>,
): ts.Expression {
  const parts = path.split(/\{(?<name>[^}]+)\}/u);

  if (parts.length === 1) return f.createNoSubstitutionTemplateLiteral(path);

  const spans: ts.TemplateSpan[] = [];
  for (let index = 1; index < parts.length; index += 2) {
    const literal = parts[index + 1] ?? "";
    const isLast = index + 2 >= parts.length;
    spans.push(
      f.createTemplateSpan(
        f.createCallExpression(
          f.createIdentifier("encodeURIComponent"),
          undefined,
          [
            f.createCallExpression(f.createIdentifier("String"), undefined, [
              f.createIdentifier(identifiers.get(parts.at(index)!)!),
            ]),
          ],
        ),
        isLast
          ? f.createTemplateTail(literal)
          : f.createTemplateMiddle(literal),
      ),
    );
  }

  return f.createTemplateExpression(f.createTemplateHead(parts[0]!), spans);
}

/** The types of one operation's inputs and results. */
interface OperationTypes {
  body: () => ts.TypeNode;
  data: () => ts.TypeNode;
  error: () => ts.TypeNode;
  path: (name: string) => ts.TypeNode;
  query: () => ts.TypeNode;
}

/** Types that refer to the operation in the generated `Routes` type. */
function routeOperationTypes(operation: ClientOperation): OperationTypes {
  const operationType = typeReference(operationTypeName(operation));
  const helper = (name: string) => typeReference(name, [operationType]);
  return {
    // Route types describe only bodies the mock parses; accept any other body.
    body: () =>
      operation.body?.routeTyped === false
        ? unknownType()
        : helper("OperationBody"),
    data: () => helper("OperationData"),
    error: () => helper("OperationError"),
    path: (name) =>
      f.createIndexedAccessTypeNode(helper("OperationPath"), literalType(name)),
    query: () => helper("OperationQuery"),
  };
}

/** Types written from the operation's schemas into `script`. */
function standaloneOperationTypes(
  operation: ClientOperation,
  script: Script,
  contracts: DataContracts,
): OperationTypes {
  const { operation: requirement, pathItem } = operation.requirements;
  const parameters = contracts.parameters(pathItem, requirement);
  const located = (location: string) =>
    [...parameters.values()].filter(
      (parameter) => (parameter.data as { in: string }).in === location,
    );
  return {
    body: () => {
      const body =
        contracts.bodyType(script, requirement, parameters) ?? unknownType();
      // Multipart uploads also accept a Blob or File for binary fields.
      return operation.body?.contentType === "FormData"
        ? typeReference(
            script.importExternalType("MultipartBody", "./http-client.js"),
            [body],
          )
        : body;
    },
    data: () => contracts.responseType(script, requirement, true),
    error: () => contracts.responseType(script, requirement, false),
    path: (name) =>
      contracts.parameterType(script, parameters.get(`path:${name}`)!),
    query: () => contracts.parameterObject(script, located("query")),
  };
}

function operationMember(
  operation: ClientOperation,
  options: ClientGenerationOptions,
  types: OperationTypes,
): ts.PropertyDeclaration {
  const taken = new Set(["data", "params", "query"]);
  const identifiers = new Map<string, string>();
  const parameters: ts.ParameterDeclaration[] = [];

  for (const pathParameter of operation.pathParameters) {
    const identifier = uniqueName(camelCase(pathParameter.name), taken);
    identifiers.set(pathParameter.name, identifier);
    parameters.push(
      parameter(
        identifier,
        pathParameter.declared
          ? types.path(pathParameter.name)
          : f.createUnionTypeNode([
              f.createKeywordTypeNode(ts.SyntaxKind.StringKeyword),
              f.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword),
            ]),
      ),
    );
  }

  // Required arguments come before optional ones.
  const inputs = [
    ...(operation.query === undefined
      ? []
      : [parameter("query", types.query(), !operation.query.required)]),
    ...(operation.body === undefined
      ? []
      : [parameter("data", types.body(), !operation.body.required)]),
  ];

  parameters.push(
    ...inputs.filter((input) => input.questionToken === undefined),
    ...inputs.filter((input) => input.questionToken !== undefined),
  );

  parameters.push(
    f.createParameterDeclaration(
      undefined,
      undefined,
      "params",
      undefined,
      typeReference("RequestParams"),
      f.createObjectLiteralExpression(),
    ),
  );

  const properties: ts.ObjectLiteralElementLike[] = [
    f.createPropertyAssignment(
      "path",
      pathExpression(operation.path, identifiers),
    ),
    f.createPropertyAssignment(
      "method",
      f.createStringLiteral(operation.method.toUpperCase()),
    ),
  ];

  if (operation.query !== undefined) {
    properties.push(f.createShorthandPropertyAssignment("query"));
  }
  if (operation.body !== undefined) {
    properties.push(
      f.createPropertyAssignment("body", f.createIdentifier("data")),
    );
  }
  if (operation.secure) {
    properties.push(f.createPropertyAssignment("secure", f.createTrue()));
  }
  if (operation.body?.contentType !== undefined) {
    properties.push(
      f.createPropertyAssignment(
        "type",
        f.createPropertyAccessExpression(
          f.createIdentifier("ContentType"),
          operation.body.contentType,
        ),
      ),
    );
  }
  if (operation.format !== undefined) {
    properties.push(
      f.createPropertyAssignment(
        "format",
        f.createStringLiteral(operation.format),
      ),
    );
  }
  properties.push(f.createSpreadAssignment(f.createIdentifier("params")));

  let request: ts.Expression = f.createCallExpression(
    f.createPropertyAccessExpression(
      f.createPropertyAccessExpression(f.createThis(), "http"),
      "request",
    ),
    [types.data(), types.error()],
    [f.createObjectLiteralExpression(properties, true)],
  );

  if (options.unwrapResponseData) {
    request = f.createCallExpression(
      f.createPropertyAccessExpression(request, "then"),
      undefined,
      [
        f.createArrowFunction(
          undefined,
          undefined,
          [parameter("response")],
          undefined,
          f.createToken(ts.SyntaxKind.EqualsGreaterThanToken),
          f.createPropertyAccessExpression(
            f.createIdentifier("response"),
            "data",
          ),
        ),
      ],
    );
  }

  return withComment(
    f.createPropertyDeclaration(
      undefined,
      operation.name,
      undefined,
      undefined,
      f.createArrowFunction(
        undefined,
        undefined,
        parameters,
        undefined,
        f.createToken(ts.SyntaxKind.EqualsGreaterThanToken),
        request,
      ),
    ),
    operationJsDoc(operation),
  );
}

function moduleStatements(
  module: ClientModule,
  options: ClientGenerationOptions,
): ts.Statement[] {
  const helpers = new Set(["OperationData", "OperationError"]);
  let usesContentType = false;

  for (const operation of module.operations) {
    if (operation.pathParameters.some(({ declared }) => declared)) {
      helpers.add("OperationPath");
    }
    if (operation.query !== undefined) helpers.add("OperationQuery");
    if (operation.body !== undefined) helpers.add("OperationBody");
    if (operation.body?.contentType !== undefined) usesContentType = true;
  }

  return [
    namedImport(["Routes"], "../types/index.js", true),
    namedImport([...helpers].sort(), "../counterfact-types/index.js", true),
    namedImport(
      [...(usesContentType ? ["ContentType"] : []), "HttpClient"],
      "./http-client.js",
      false,
    ),
    namedImport(["HttpProvider", "RequestParams"], "./http-client.js", true),
    ...module.operations.map((operation) =>
      typeAlias(
        operationTypeName(operation),
        f.createIndexedAccessTypeNode(
          routeTypeReference("Routes", operation.path),
          literalType(operation.method.toUpperCase()),
        ),
        false,
      ),
    ),
    f.createClassDeclaration(
      exportModifier(),
      module.name,
      undefined,
      undefined,
      [
        ...providerMembers(),
        ...module.operations.map((operation) =>
          operationMember(operation, options, routeOperationTypes(operation)),
        ),
      ],
    ),
  ];
}

/**
 * Generates the module, data contract and barrel files of a standalone
 * client, keyed by their path inside the client directory.
 */
async function standaloneFiles(
  specification: Specification,
  modules: readonly ClientModule[],
  options: ClientGenerationOptions,
): Promise<Map<string, string>> {
  const repository = new Repository();
  const contracts = new DataContracts(specification, {
    directory: CLIENT_DIRECTORY,
    reserved: [
      ...RESERVED_MODULE_NAMES,
      options.apiClassName ?? "Api",
      ...modules.map(({ name }) => name),
    ],
    typePrefix: options.typePrefix,
    typeSuffix: options.typeSuffix,
  });

  // Declare every schema, including those no operation refers to.
  for (const [name, refUrl] of contracts.entries) {
    contracts.declare(
      repository.get(
        `${CLIENT_DIRECTORY}/${DATA_CONTRACTS_DIRECTORY}/${name}.ts`,
      ),
      refUrl,
    );
  }

  for (const module of modules) {
    const script = repository.get(`${CLIENT_DIRECTORY}/${module.name}.ts`);
    script.reservedNames.add(module.name);
    // Import the provider first so data contracts cannot claim its names.
    if (module.operations.some(({ body }) => body?.contentType !== undefined)) {
      script.importExternal("ContentType", "./http-client.js");
    }
    script.importExternal("HttpClient", "./http-client.js");
    script.importExternalType("HttpProvider", "./http-client.js");
    script.importExternalType("RequestParams", "./http-client.js");
    if (
      module.operations.some(({ body }) => body?.contentType === "FormData")
    ) {
      script.importExternalType("MultipartBody", "./http-client.js");
    }

    const declaration = f.createClassDeclaration(
      exportModifier(),
      module.name,
      undefined,
      undefined,
      [
        ...providerMembers(),
        ...module.operations.map((operation) =>
          operationMember(
            operation,
            options,
            standaloneOperationTypes(operation, script, contracts),
          ),
        ),
      ],
    );
    script.statementBuilders.set(module.name, () => [declaration]);
  }

  await repository.finished();

  const files = new Map<string, string>();
  const contractNames: string[] = [];
  const prefix = `${CLIENT_DIRECTORY}/`;

  for (const [path, script] of repository.scripts) {
    script.comments = GENERATED_COMMENTS;
    const relativePath = path.slice(prefix.length);
    if (relativePath.startsWith(`${DATA_CONTRACTS_DIRECTORY}/`)) {
      contractNames.push(nodePath.posix.basename(relativePath, ".ts"));
    }
    files.set(relativePath, await script.contents());
  }

  if (contractNames.length > 0) {
    files.set(
      "data-contracts.ts",
      await formatStatements(
        contractNames
          .sort()
          .map((name) =>
            f.createExportDeclaration(
              undefined,
              false,
              undefined,
              f.createStringLiteral(`./${DATA_CONTRACTS_DIRECTORY}/${name}.js`),
            ),
          ),
        GENERATED_COMMENTS,
      ),
    );
  }

  return files;
}

function dataContractStatements(
  specification: Specification,
  { typePrefix = "", typeSuffix = "" }: ClientGenerationOptions,
  classNames: readonly string[],
): ts.Statement[] {
  // `index.ts` re-exports these alongside the HTTP provider and the module and
  // API classes, whose explicit exports would shadow a contract of the same name.
  const taken = new Set(
    [...RESERVED_MODULE_NAMES, ...classNames].map((name) => name.toLowerCase()),
  );
  const statements: ts.Statement[] = [];

  const { enumStyle = "union" } = specification.typeOptions;

  specification
    .getRequirement("#/components/schemas")
    ?.forEach((schema, name) => {
      const typeName = uniqueName(
        `${typePrefix}${pascalCase(name)}${typeSuffix}`,
        taken,
      );
      if (enumStyle !== "union" && namedEnumMembers(schema.data)) {
        // Re-export the declaration from types/ so both share one enum.
        const coder = new SchemaTypeCoder(
          new Requirement(
            {
              $ref: `#/components/schemas/${name.replaceAll("~", "~0").replaceAll("/", "~1")}`,
            },
            "",
            specification,
          ),
        );
        statements.push(
          f.createExportDeclaration(
            undefined,
            false,
            f.createNamedExports([
              f.createExportSpecifier(
                false,
                coder.names().next().value!,
                typeName,
              ),
            ]),
            f.createStringLiteral(
              `../${coder.modulePath().replace(/\.ts$/u, ".js")}`,
            ),
          ),
        );
        return;
      }
      statements.push(
        typeAlias(
          typeName,
          f.createIndexedAccessTypeNode(
            typeReference("Schemas"),
            literalType(name),
          ),
        ),
      );
    });

  return statements.length === 0
    ? []
    : [namedImport(["Schemas"], "../types/index.js", true), ...statements];
}

function apiClassStatements(
  modules: readonly ClientModule[],
  apiClassName: string,
  hasDataContracts: boolean,
  hasDataContractValues = false,
): ts.Statement[] {
  const taken = new Set(["constructor", "http"]);
  const members = modules.map((module) => ({
    module,
    property: uniqueName(camelCase(module.name), taken),
  }));

  return [
    f.createExportDeclaration(
      undefined,
      false,
      undefined,
      f.createStringLiteral("./http-client.js"),
    ),
    ...(hasDataContracts
      ? [
          f.createExportDeclaration(
            undefined,
            !hasDataContractValues,
            undefined,
            f.createStringLiteral("./data-contracts.js"),
          ),
        ]
      : []),
    namedImport(["HttpClient"], "./http-client.js", false),
    namedImport(["HttpProvider"], "./http-client.js", true),
    ...modules.map(({ name }) => namedImport([name], `./${name}.js`, false)),
    ...(modules.length === 0
      ? []
      : [
          f.createExportDeclaration(
            undefined,
            false,
            f.createNamedExports(
              modules.map(({ name }) =>
                f.createExportSpecifier(false, undefined, name),
              ),
            ),
          ),
        ]),
    withComment(
      f.createClassDeclaration(
        exportModifier(),
        apiClassName,
        undefined,
        undefined,
        [
          ...members.map(({ module, property }) =>
            f.createPropertyDeclaration(
              [
                f.createModifier(ts.SyntaxKind.PublicKeyword),
                f.createModifier(ts.SyntaxKind.ReadonlyKeyword),
              ],
              property,
              undefined,
              typeReference(module.name),
              undefined,
            ),
          ),
          ...providerMembers(
            members.map(({ module, property }) =>
              f.createExpressionStatement(
                f.createAssignment(
                  f.createPropertyAccessExpression(f.createThis(), property),
                  f.createNewExpression(
                    f.createIdentifier(module.name),
                    undefined,
                    [f.createIdentifier("http")],
                  ),
                ),
              ),
            ),
          ),
        ],
      ),
      jsDoc([
        "Every client module, sharing one HTTP provider.",
        "",
        "Configure the base URL, credentials, headers and `fetch` implementation",
        "on the provider: `new Api(new HttpClient({ baseUrl }))`. Pass any",
        "`HttpProvider` implementation to send requests some other way.",
      ]),
    ),
  ];
}

/** The default, fetch-based `HttpProvider` copied into every client. */
function templatePath(): string {
  const fileName = "http-client.ts";
  const candidates = [
    // Installed package: dist/templates/client
    nodePath.join(__dirname, "templates", "client", fileName),
    // Source checkout: templates/client next to src
    nodePath.join(__dirname, "..", "templates", "client", fileName),
  ];
  const found = candidates.find((candidate) => existsSync(candidate));

  if (found === undefined) {
    throw new Error("Could not find the HTTP client template.");
  }

  return found;
}

async function isGeneratedClientFile(path: string): Promise<boolean> {
  const contents = await fs.readFile(path, "utf8").catch(() => "");
  return contents.startsWith(`// ${GENERATED_COMMENTS[0]}`);
}

/**
 * Renames the module that shares the API class's name, choosing a name no
 * other module (or the API class) uses, since names are also file names.
 */
function renameApiCollision(
  modules: ClientModule[],
  apiClassName: string,
): ClientModule[] {
  const taken = new Set(
    [apiClassName, ...modules.map((module) => module.name)].map((name) =>
      name.toLowerCase(),
    ),
  );
  return modules.map((module) =>
    module.name.toLowerCase() === apiClassName.toLowerCase()
      ? { ...module, name: uniqueName(`${module.name}Module`, taken) }
      : module,
  );
}

/**
 * Generates a typed API client for `specification` in
 * `destination/client`, with one class per module.
 *
 * By default the client reuses Counterfact's generated `Routes` and `Schemas`
 * types, so it must be written alongside (and after) the generated `types`
 * directory. A standalone client declares its own types instead.
 * Previously generated client files that no longer apply are removed; other
 * files in the directory are left alone.
 *
 * @returns The written file paths, relative to `destination`.
 */
export async function generateClient(
  specification: Specification,
  destination: string,
  options: ClientGenerationOptions = {},
): Promise<string[]> {
  const apiClassName = options.apiClassName ?? "Api";

  const affixes = {
    moduleClassSuffix: options.moduleClassSuffix,
    typePrefix: options.typePrefix,
    typeSuffix: options.typeSuffix,
  };
  for (const [key, affix] of Object.entries(affixes)) {
    if (!/^[\w$]*$/u.test(affix ?? "")) {
      throw new Error(
        `The client option ${key} must contain only identifier characters (received ${JSON.stringify(affix)}).`,
      );
    }
  }

  // A prefix starts every type name, so it cannot start with a digit.
  if (/^\d/u.test(options.typePrefix ?? "")) {
    throw new Error(
      `The client option typePrefix must not start with a digit (received ${JSON.stringify(options.typePrefix)}).`,
    );
  }

  if (!isClassName(apiClassName)) {
    throw new Error(
      `The API class name ${JSON.stringify(apiClassName)} is not a valid TypeScript class name.`,
    );
  }

  if (RESERVED_MODULE_NAMES.has(apiClassName)) {
    throw new Error(
      `The API class name ${JSON.stringify(apiClassName)} is reserved by the generated client.`,
    );
  }

  const modules = renameApiCollision(
    collectClientModules(specification, options),
    apiClassName,
  );

  const directory = nodePath.join(destination, CLIENT_DIRECTORY);
  const files = new Map<string, string>();

  files.set("http-client.ts", await fs.readFile(templatePath(), "utf8"));

  // Standalone contracts may declare enums, which are values.
  let hasDataContractValues = options.standalone === true;

  if (options.standalone) {
    for (const [path, contents] of await standaloneFiles(
      specification,
      modules,
      options,
    )) {
      files.set(path, contents);
    }
  } else {
    const dataContracts = dataContractStatements(specification, options, [
      apiClassName,
      ...modules.map((module) => module.name),
    ]);
    hasDataContractValues = dataContracts.some(
      (statement) => ts.isExportDeclaration(statement) && !statement.isTypeOnly,
    );

    if (dataContracts.length > 0) {
      files.set(
        "data-contracts.ts",
        await formatStatements(dataContracts, GENERATED_COMMENTS),
      );
    }

    for (const module of modules) {
      files.set(
        `${module.name}.ts`,
        await formatStatements(
          moduleStatements(module, options),
          GENERATED_COMMENTS,
        ),
      );
    }
  }

  const hasDataContracts = files.has("data-contracts.ts");

  files.set(
    "index.ts",
    await formatStatements(
      apiClassStatements(
        modules,
        apiClassName,
        hasDataContracts,
        hasDataContractValues,
      ),
      GENERATED_COMMENTS,
    ),
  );

  for (const subdirectory of ["", DATA_CONTRACTS_DIRECTORY]) {
    const entries = await fs
      .readdir(nodePath.join(directory, subdirectory))
      .catch(() => []);
    for (const entry of entries) {
      const fileName = nodePath.posix.join(subdirectory, entry);
      const path = nodePath.join(directory, fileName);
      if (
        !files.has(fileName) &&
        entry.endsWith(".ts") &&
        (await isGeneratedClientFile(path))
      ) {
        debug("removing stale client file %s", path);
        await fs.rm(path);
      }
    }
  }

  await Promise.all(
    [...files].map(async ([fileName, contents]) => {
      const path = nodePath.join(directory, fileName);
      await fs.mkdir(nodePath.dirname(path), { recursive: true });
      await fs.writeFile(path, contents);
    }),
  );

  return [...files.keys()].map((fileName) => `${CLIENT_DIRECTORY}/${fileName}`);
}
