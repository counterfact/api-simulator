import Ajv from "ajv";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import ts from "typescript";
import { format } from "prettier";

import {
  exportedConst,
  functionType,
  importDeclaration,
  objectExpression,
  parameter,
  printStatements,
  stringType,
  typeReference,
  unknownType,
} from "./ast.js";
import type { ClientResponseSchemas } from "./client-response-schemas.js";

const helpers = new Map([
  ["ajv/dist/runtime/equal", "equal"],
  ["ajv/dist/runtime/ucs2length", "ucs2length"],
]);

/** Ajv's standalone ESM still uses CommonJS for its runtime helpers. */
function importHelpers(code: string) {
  const file = ts.createSourceFile(
    "validators.js",
    code,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.JS,
  );
  const imports = new Set<string>();
  const replacements: { start: number; end: number; helper: string }[] = [];
  function visit(node: ts.Node): void {
    if (
      ts.isCallExpression(node) &&
      ts.isIdentifier(node.expression) &&
      node.expression.text === "require"
    ) {
      const [argument] = node.arguments;
      const helper =
        argument && ts.isStringLiteral(argument)
          ? helpers.get(argument.text)
          : undefined;
      const access = node.parent;
      if (
        !helper ||
        !ts.isPropertyAccessExpression(access) ||
        access.name.text !== "default"
      ) {
        throw new Error(
          `Unsupported dependency in generated response validator: ${node.getText(file)}`,
        );
      }
      imports.add(helper);
      replacements.push({
        start: access.getStart(file),
        end: access.getEnd(),
        helper,
      });
    }
    ts.forEachChild(node, visit);
  }
  visit(file);
  for (const { start, end, helper } of replacements.reverse()) {
    code = code.slice(0, start) + helper + code.slice(end);
  }
  return {
    code,
    imports: [...imports].map((helper) =>
      importDeclaration(helper, "@counterfact/client/validation-helpers"),
    ),
  };
}

export async function standaloneClientValidators(
  metadata: NonNullable<ReturnType<ClientResponseSchemas["output"]>>,
): Promise<string> {
  const Validator = metadata.draft === "7" ? Ajv : Ajv2020;
  const ajv = new Validator({
    strict: false,
    ownProperties: true,
    strictNumbers: true,
    validateFormats: false,
    code: { source: true, esm: true, lines: true },
  });
  ajv.addSchema(metadata.schema);
  for (const uri of Object.values(metadata.validators)) {
    const validate = ajv.getSchema(uri);
    if (validate && "$async" in validate) {
      throw new Error(
        "Fetch client response schemas must use synchronous validation",
      );
    }
  }
  // Ajv assigns its own bindings such as schema12. Give public exports
  // a distinct prefix so a larger schema graph cannot redeclare them.
  const entries = Object.entries(metadata.validators).map(
    ([key, uri], index) => ({
      key,
      uri,
      name: `validateResponse${index}`,
    }),
  );
  const standalone = importHelpers(
    standaloneCode(
      ajv,
      Object.fromEntries(entries.map(({ name, uri }) => [name, uri])),
    ),
  );
  const boolean = ts.factory.createKeywordTypeNode(
    ts.SyntaxKind.BooleanKeyword,
  );
  const validatorType = functionType(
    [parameter("body", unknownType())],
    boolean,
  );
  const registry = exportedConst(
    "responseValidators",
    objectExpression(
      entries.map(({ key, name }) => [key, ts.factory.createIdentifier(name)]),
    ),
    typeReference("Readonly", [
      typeReference("Record", [stringType(), validatorType]),
    ]),
  );

  // Ajv emits JavaScript. Keep it in the TypeScript build with a typed registry
  // so consumers can emit the validator along with the rest of the client.
  return format(
    "// @ts-nocheck\n// Generated by Counterfact and Ajv. Do not edit.\n" +
      printStatements(standalone.imports) +
      standalone.code +
      printStatements([registry]),
    { parser: "typescript" },
  );
}
